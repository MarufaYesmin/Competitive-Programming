void abcd(){
    ll n; cin>>n;
    vector<ll> v(n);
    for(auto &a:v) cin>>a;

    ll count=0,minPrice=LLONG_MAX;
    for(ll i=n-1;i>=0;i--){
        if(v[i]>minPrice){
            count++;
        }
        else{   
            minPrice=min(minPrice,v[i]);
        }
    }
    cout<<count<<endl;
}

