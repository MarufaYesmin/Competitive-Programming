void abcd() {
    ll n; cin>>n;

    ll ans=LLONG_MAX;

    for (ll i=0;i<n;i++) {
        ll d,s; cin>>d>>s;

        ans = min(ans,d+(s-1)/2);
    }
    cout<<ans<<endl;
}

